def predict_in_domain(cfg):
    """
    In-domain prediction with validation-only tuning.

    DATA USAGE:
      1) Load trained model + normal center/prototypes.
      2) Load NORMAL validation only.
      3) Split normal validation into FIT and TUNE subsets.
      4) Generate synthetic anomalies from TUNE normal sequences only.
      5) Fit robust median/MAD normalization on FIT normals only.
      6) Tune ONLY MLM/center weights on:
             real TUNE normals vs synthetic TUNE anomalies.
         No real anomalous validation labels are used.
      7) Refit robust normalizer on all normal validation samples and freeze
         selected weights + fixed-percentile threshold.
      8) ONLY NOW load the held-out TEST set.
      9) Apply frozen scoring to TEST.
     10) Use TEST labels only for final evaluation.
    """
    out_dir = ensure_output_dir(cfg)

    seed = int(cfg["experiment"].get("seed", 42))
    set_seed(seed)
    device = get_device(cfg["training"].get("device", "auto"))

    mode_cfg = cfg["datasets"]["in_domain"]
    dataset_name = mode_cfg["dataset_name"]

    print("=" * 80)
    print("[Stage] PREDICT ONLY")
    print("[Mode] in_domain")
    print(f"[Dataset] {dataset_name}")
    print(f"[Scoring version] {ROBUST_SCORING_VERSION}")
    print("=" * 80)

    # STEP 1 - model/center
    print("[STEP 1/10] Load trained model, tokenizer, and normal center/prototypes")
    model, tokenizer, center = load_saved_model_tokenizer_center(
        cfg=cfg,
        out_dir=out_dir,
        device=device,
        center_filename="normal_center.pt",
    )

    # STEP 2 - normal validation only
    print("[STEP 2/10] Load NORMAL validation samples only")
    val_normal_df = load_sequences_for_dataset(
        cfg,
        dataset=dataset_name,
        split=mode_cfg["val_split"],
        normal_only=True,
    )
    print(f"[Normal validation sequences] {len(val_normal_df)}")

    # STEPS 3-7 - validation-only tuning and freezing
    print("[STEP 3-7/10] Validation-only WEIGHT tuning; percentile fixed at 95")
    robust_params, robust_threshold, robust_val_normal_scores, tuning_df = (
        fit_and_tune_robust_scoring(
            cfg=cfg,
            val_normal_df=val_normal_df,
            model=model,
            tokenizer=tokenizer,
            center=center,
            device=device,
            seed=seed,
            desc_prefix=f"{dataset_name} validation tuning",
        )
    )

    save_json(robust_params, out_dir / "robust_scoring_params.json")
    tuning_df.to_csv(out_dir / "robust_tuning_search.csv", index=False)
    robust_val_normal_scores.to_csv(
        out_dir / "robust_normal_validation_scores.csv", index=False
    )

    print("[TEST HAS NOT BEEN LOADED YET]")

    # STEP 8 - only now load test
    print("[STEP 8/10] Load held-out TEST only after tuning is frozen")
    test_df = load_sequences_for_dataset(
        cfg,
        dataset=dataset_name,
        split=mode_cfg["test_split"],
        normal_only=mode_cfg.get("test_normal_only", False),
    )
    print(f"[Test sequences] {len(test_df)}")

    test_loader = make_loader(cfg, test_df, tokenizer, shuffle=False)

    # STEP 9 - score/apply frozen params
    print("[STEP 9/10] Score TEST and apply FROZEN robust parameters")
    test_raw_scores = score_loader(
        model,
        test_loader,
        center,
        device,
        alpha_mlm=COMPONENT_EXTRACTION_MLM_WEIGHT,
        beta_center=COMPONENT_EXTRACTION_CENTER_WEIGHT,
        desc="Scoring held-out TEST components",
    )
    robust_test_scores = apply_robust_score_normalization(
        test_raw_scores, robust_params
    )
    robust_test_scores["prediction"] = (
        robust_test_scores["score"] > robust_threshold
    ).astype(int)

    # STEP 10 - final evaluation only
    print("[STEP 10/10] Use TEST labels only for final metrics")
    metrics = evaluate_scores(
        robust_test_scores,
        robust_threshold,
        normal_label=0,
    )

    save_classification_report_files(metrics, out_dir, prefix="test")
    robust_test_scores.to_csv(
        out_dir / cfg["outputs"].get("predictions_file", "predictions.csv"),
        index=False,
    )

    save_json(
        {
            "stage": "predict",
            "mode": "in_domain",
            "dataset": dataset_name,
            "metrics": metrics,
            "robust_scoring": robust_params,
            "robust_threshold": float(robust_threshold),
        },
        out_dir / cfg["outputs"].get("results_file", "results.json"),
    )

    print("=" * 80)
    print("[IN-DOMAIN PREDICTION FINISHED]")
    print("[Weight-Tuned Robust FINAL TEST Classification Report]")
    print(metrics["classification_report_text"])
    print("=" * 80)

def run_in_domain(cfg, config_path: str):
    """
    Full in-domain pipeline:
        train
        predict
    """

    train_in_domain(cfg, config_path)
    predict_in_domain(cfg)


